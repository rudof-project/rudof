use pyo3::prelude::*;
use rudof_lib::formats::{BackendSpec, DdlDialect, PgSchemaFormat, ResultPgSchemaValidationFormat};

pyenum! {
    /// Property graph schema formats.
    "PgSchemaFormat": PyPgSchemaFormat => PgSchemaFormat, default = PgSchemaC, from_str {
        /// PgSchemaC - compact property graph schema syntax.
        PgSchemaC => PgSchemaC,
    }
}

pyenum! {
    /// Output formats for property graph schema validation results.
    "ResultPgSchemaValidationFormat": PyResultPgSchemaValidationFormat
        => ResultPgSchemaValidationFormat, default = Compact, from_str {
        /// Compact - concise validation output.
        Compact => Compact,
        /// Verbose output including validation details.
        Details => Details,
        /// JSON - machine-readable JSON serialization.
        Json    => Json,
        /// CSV - comma-separated values for spreadsheet tools.
        Csv     => Csv,
    }
}

pyenum! {
    /// Target dialect for the property graph DDL generated by `pg_db_ddl`.
    "DdlDialect": PyDdlDialect => DdlDialect, default = Cypher {
        /// Cypher-style DDL.
        Cypher => Cypher,
        /// ISO GQL-style graph type DDL.
        Gql    => Gql,
    }
}

