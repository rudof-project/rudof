//! Remote SPARQL endpoints on wasm, with JSPI (WebAssembly JavaScript Promise
//! Integration).
//!
//! The validators and the SPARQL engine query their data through synchronous
//! traits (`NeighsRDF`, `QueryRDF`), while the only way to make an HTTP request
//! from wasm is JavaScript's asynchronous `fetch`. JSPI bridges the two: an
//! export marked `#[wasm_bindgen(jspi)]` returns a JavaScript `Promise`, and
//! inside it synchronous Rust code can suspend the whole WebAssembly stack
//! until another `Promise` settles, while the JavaScript event loop keeps
//! running.
//!
//! The bindings must run every operation that may query an endpoint inside
//! such an export, wrapped in [`run_suspendable`]. Elsewhere (e.g. in an
//! ordinary synchronous export), suspending is impossible, and endpoint
//! requests fail with [`OxigraphEndpointError::NotSuspendable`] instead.
//!
//! A module built with this feature needs a runtime with JSPI and exnref
//! (e.g. Chrome 137+, Node.js 25+): the glue generated by `wasm-bindgen` fails
//! to load elsewhere.

// `jspi_block_on_promise` is marked deprecated while JSPI support in
// wasm-bindgen is experimental.
#![allow(deprecated)]

use crate::rdf_impl::OxigraphEndpointError;
use crate::rdf_impl::oxigraph::http::{HttpResponse, REQUEST_TIMEOUT, SendError};
use js_sys::futures::{JsFuture, future_to_promise, jspi_block_on_promise};
use js_sys::{Function, Object, Promise, Reflect};
use std::cell::{Cell, RefCell};
use std::future::Future;
use std::ops::Add;
use std::rc::Rc;
use std::time::Duration;
use wasm_bindgen::{JsCast, JsValue};

thread_local! {
    /// Whether the code running now may suspend: it was called through
    /// [`run_suspendable`], and is not inside a suspension of its own.
    ///
    /// While a suspended call waits, other JavaScript code (and other wasm
    /// exports) can run, so this is cleared for the duration of each
    /// suspension and set again when the call resumes.
    static SUSPENDABLE: Cell<bool> = const { Cell::new(false) };

    /// The `fetch` function set with [`set_fetch`], if any.
    static FETCH: RefCell<Option<Function>> = const { RefCell::new(None) };
}

/// Runs `f` allowing it to wait for remote SPARQL endpoints.
///
/// Must only be called from a `#[wasm_bindgen(jspi)]` export (directly, not
/// from a function it calls back into JavaScript): suspending anywhere else
/// throws a `SuspendError` through the Rust frames, leaving the objects they
/// borrowed unusable.
pub fn run_suspendable<R>(f: impl FnOnce() -> R) -> R {
    let outer = SUSPENDABLE.replace(true);
    let result = f();
    SUSPENDABLE.set(outer);
    result
}

/// Sets the function used to make HTTP requests, with the signature of
/// `fetch` (`(url, init) => Promise<Response>`), or goes back to the global
/// `fetch` with `None`.
///
/// It can add headers (e.g. `Api-User-Agent` for Wikimedia endpoints), send
/// requests through a proxy (e.g. for endpoints without CORS), cache, or
/// mock responses in tests. Only `status`, `headers.get` and `text()` of the
/// response are used.
pub fn set_fetch(fetch: Option<Function>) {
    FETCH.with(|f| *f.borrow_mut() = fetch);
}

/// Runs `future` to completion, suspending the WebAssembly stack with JSPI
/// until it is done.
pub(crate) fn block_on<T: 'static>(
    future: impl Future<Output = Result<T, OxigraphEndpointError>> + 'static,
) -> Result<T, OxigraphEndpointError> {
    if !SUSPENDABLE.get() {
        return Err(OxigraphEndpointError::NotSuspendable);
    }
    let slot = Rc::new(RefCell::new(None));
    let promise = future_to_promise({
        let slot = Rc::clone(&slot);
        async move {
            let result = future.await;
            *slot.borrow_mut() = Some(result);
            Ok(JsValue::UNDEFINED)
        }
    });
    SUSPENDABLE.set(false);
    let settled = jspi_block_on_promise(&promise);
    SUSPENDABLE.set(true);
    if let Err(error) = settled {
        return Err(OxigraphEndpointError::FetchError {
            message: describe(&error),
        });
    }
    slot.borrow_mut().take().unwrap_or_else(|| {
        Err(OxigraphEndpointError::FetchError {
            message: "the request finished without a result".to_string(),
        })
    })
}

/// A point in time, in milliseconds since the epoch: `std::time::Instant`
/// panics on `wasm32-unknown-unknown`.
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub(crate) struct Instant(f64);

impl Instant {
    pub(crate) fn now() -> Instant {
        Instant(js_sys::Date::now())
    }

    pub(crate) fn saturating_duration_since(&self, earlier: Instant) -> Duration {
        Duration::from_secs_f64((self.0 - earlier.0).max(0.0) / 1000.0)
    }
}

impl Add<Duration> for Instant {
    type Output = Instant;

    fn add(self, duration: Duration) -> Instant {
        Instant(self.0 + duration.as_secs_f64() * 1000.0)
    }
}

/// Waits for `duration` with `setTimeout`.
pub(crate) async fn sleep(duration: Duration) {
    let millis = JsValue::from(duration.as_secs_f64() * 1000.0);
    let promise = Promise::new(&mut |resolve, _reject| match global_function("setTimeout") {
        Ok(set_timeout) => {
            let _ = set_timeout.call2(&JsValue::UNDEFINED, &resolve, &millis);
        },
        Err(_) => {
            let _ = resolve.call0(&JsValue::UNDEFINED);
        },
    });
    let _ = JsFuture::from(promise).await;
}

/// Sends a GET request to `url` with `Accept: <accept>`, through the
/// function set with [`set_fetch`] or the global `fetch`.
pub(crate) async fn fetch(url: &str, accept: &str) -> Result<HttpResponse, SendError> {
    let fatal = |error: JsValue| {
        SendError::Fatal(OxigraphEndpointError::FetchError {
            message: describe(&error),
        })
    };
    let fetch = match FETCH.with(|f| f.borrow().clone()) {
        Some(fetch) => fetch,
        None => global_function("fetch").map_err(fatal)?,
    };

    let headers = Object::new();
    Reflect::set(&headers, &"Accept".into(), &accept.into()).map_err(fatal)?;
    let init = Object::new();
    Reflect::set(&init, &"headers".into(), &headers).map_err(fatal)?;
    if let Some(signal) = timeout_signal(REQUEST_TIMEOUT) {
        Reflect::set(&init, &"signal".into(), &signal).map_err(fatal)?;
    }

    let pending = fetch.call2(&JsValue::UNDEFINED, &url.into(), &init).map_err(fatal)?;
    // `fetch` rejects on network errors, CORS rejections and timeouts alike.
    let response = JsFuture::from(Promise::resolve(&pending)).await.map_err(|error| {
        SendError::Transient(OxigraphEndpointError::FetchError {
            message: describe(&error),
        })
    })?;

    let status = Reflect::get(&response, &"status".into())
        .ok()
        .and_then(|status| status.as_f64())
        .filter(|status| (0.0..1000.0).contains(status))
        .ok_or_else(|| fatal(JsValue::from_str("fetch did not return a Response")))?;
    let retry_after = Reflect::get(&response, &"headers".into()).ok().and_then(|headers| {
        let get = Reflect::get(&headers, &"get".into())
            .ok()?
            .dyn_into::<Function>()
            .ok()?;
        get.call1(&headers, &"retry-after".into()).ok()?.as_string()
    });
    let text = Reflect::get(&response, &"text".into())
        .and_then(|text| text.dyn_into::<Function>())
        .map_err(fatal)?;
    let body = JsFuture::from(Promise::resolve(&text.call0(&response).map_err(fatal)?))
        .await
        .map_err(|error| {
            SendError::Transient(OxigraphEndpointError::FetchError {
                message: describe(&error),
            })
        })?;

    // In range (checked above).
    #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
    let status = status as u16;
    Ok(HttpResponse {
        status,
        retry_after,
        body: body.as_string().unwrap_or_default(),
    })
}

/// `AbortSignal.timeout(timeout)`, where available.
fn timeout_signal(timeout: Duration) -> Option<JsValue> {
    let abort_signal = Reflect::get(&js_sys::global(), &"AbortSignal".into()).ok()?;
    let timeout_fn = Reflect::get(&abort_signal, &"timeout".into())
        .ok()?
        .dyn_into::<Function>()
        .ok()?;
    let millis = JsValue::from(timeout.as_secs_f64() * 1000.0);
    timeout_fn.call1(&abort_signal, &millis).ok()
}

fn global_function(name: &str) -> Result<Function, JsValue> {
    Reflect::get(&js_sys::global(), &name.into())?
        .dyn_into::<Function>()
        .map_err(|_| JsValue::from_str(&format!("`{name}` is not available in this JavaScript environment")))
}

/// A readable description of a JavaScript error, with its cause (Node.js's
/// `fetch` reports the reason for a network error there).
fn describe(error: &JsValue) -> String {
    match error.dyn_ref::<js_sys::Error>() {
        Some(error) => {
            let mut message = format!("{}: {}", String::from(error.name()), String::from(error.message()));
            let cause = error.cause();
            if !cause.is_undefined() && !cause.is_null() {
                message.push_str(&format!(" ({})", describe(&cause)));
            }
            message
        },
        None => error.as_string().unwrap_or_else(|| format!("{error:?}")),
    }
}
